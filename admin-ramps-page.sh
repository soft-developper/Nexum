#!/usr/bin/env bash
# ============================================================
# admin-ramps-page.sh
#
# Add a dedicated admin "Ramps" page: fiat on/off-ramp analytics so admins see
# the same trading reality users see on their dashboards, aggregated
# platform-wide. Gated on the existing VIEW_ANALYTICS permission.
#
# Shows: KYC'd users + status + funnel (approved/pending/rejected, individual/
# business), on-ramp & off-ramp volume in USD (24h/7d/all), per-currency /
# corridor breakdown, health signals (pending deposits, failed/returned drains,
# rejected KYC), and a provider breakdown (future-proof for multi-provider).
#
# Changes:
#   API  EDIT src/routes/adminManage.ts      (+ GET /admin/manage/ramps handler)
#   WEB  NEW  app/admin/ramps/page.tsx        (the page, mirrors analytics page)
#   WEB  EDIT components/admin/AdminShell.tsx (nav entry + icon + guard-map path)
#
# Reuses the overview's USD convention (getCachedRates, USDC/USD == 1). Only
# terminal states count toward volume (deposits: payment_processed; drains:
# payment_processed). No em-dashes (per house style).
#
# v2 delivery: base64 -> temp -> decode -> verify (marker) before place; edits
# are anchored byte-exact and abort cleanly if an anchor is missing. Idempotent.
# --revert removes the page and restores both edited files from backups.
#
# Usage:
#   bash admin-ramps-page.sh          # apply
#   bash admin-ramps-page.sh --revert # undo
# ============================================================
set -euo pipefail
STAMP="$(date +%Y%m%d-%H%M%S)"

if [ -d "nexum-api" ] && [ -d "nexum-web" ]; then ROOT="."
elif [ -f "../nexum-api/package.json" ]; then ROOT=".."
else echo "ERROR: run from the repo root (~/AfriFX)." >&2; exit 1; fi
API="$ROOT/nexum-api"; WEB="$ROOT/nexum-web"

MANAGE="$API/src/routes/adminManage.ts"
PAGE="$WEB/app/admin/ramps/page.tsx"
SHELL="$WEB/components/admin/AdminShell.tsx"

for f in "$MANAGE" "$SHELL"; do [ -f "$f" ] || { echo "ERROR: $f not found." >&2; exit 1; }; done

# ---- revert -----------------------------------------------------------------
if [ "${1:-}" = "--revert" ]; then
  echo "Reverting admin Ramps page..."
  for f in "$MANAGE" "$SHELL"; do
    BK="$(ls -t "$f".bak.* 2>/dev/null | head -1 || true)"
    [ -n "$BK" ] && { cp "$BK" "$f"; echo "  restored $(basename "$f")"; }
  done
  [ -f "$PAGE" ] && { rm -f "$PAGE"; rmdir "$(dirname "$PAGE")" 2>/dev/null || true; echo "  removed $PAGE"; }
  echo "Revert complete. Re-run per-package tsc + build."
  exit 0
fi

TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
decode_verify () { base64 --decode "$1" > "$2" 2>/dev/null || { echo "ERROR: decode $2 failed" >&2; exit 1; }; [ -s "$2" ] || { echo "ERROR: $2 empty" >&2; exit 1; }; [ -z "$3" ] || grep -qF "$3" "$2" || { echo "ERROR: marker '$3' missing in $2" >&2; exit 1; }; }
anchored () { # file oldb newb guard
  local file="$1" oldb="$2" newb="$3" guard="$4"
  if grep -qF "$guard" "$file" 2>/dev/null; then echo "  $(basename "$file"): '$guard' present - skipping"; return; fi
  decode_verify "$oldb" "$TMP/o" ""; decode_verify "$newb" "$TMP/n" ""
  local old new; old="$(cat "$TMP/o")"; new="$(cat "$TMP/n")"
  grep -qF "$old" "$file" || { echo "ERROR: anchor not found in $file - aborting." >&2; exit 1; }
  [ -f "$file.bak.$STAMP" ] || cp "$file" "$file.bak.$STAMP"
  OLD="$old" NEW="$new" python3 - "$file" <<'PY'
import os,sys
p=sys.argv[1];s=open(p).read();old=os.environ['OLD'];new=os.environ['NEW']
assert s.count(old)==1,f"anchor count {s.count(old)} in {p}"
open(p,'w').write(s.replace(old,new,1))
PY
}

